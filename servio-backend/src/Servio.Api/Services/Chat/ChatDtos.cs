using System.ComponentModel.DataAnnotations;
using Servio.Api.Common;

namespace Servio.Api.Services.Chat;

public enum MessageType : byte { Text = 1, Image = 2, System = 3 }

/// <summary>Row of #54 and result of #55/#56 (CS-27 / PS-20 list, CS-28 header).</summary>
public sealed record ConversationDto(
    Guid Id,
    ConversationStatus Status,
    bool CanSend,
    Guid ServiceRequestId,
    string RequestCode,
    string RequestTitle,
    ServiceRequestStatus RequestStatus,
    Guid? OrderId,
    OrderStatus? OrderStatus,
    CounterpartDto Counterpart,
    LastMessageDto? LastMessage,
    int UnreadCount,
    DateTimeOffset CreatedAt);

/// <summary>
/// The other person. A partner sees the customer's short name ("An N."); a customer sees the partner's full name.
/// Phone numbers are never included (calls go through the order screen after ACCEPTED, F-ORD-06).
/// </summary>
public sealed record CounterpartDto(Guid? PartnerProfileId, string DisplayName, string? AvatarUrl, decimal? Rating);

public sealed record LastMessageDto(string Preview, DateTimeOffset At, bool IsMine);

/// <summary>A message (#57, #58, ReceiveMessage). senderRole: CUSTOMER, PARTNER or SYSTEM.</summary>
public sealed record MessageDto(
    Guid Id,
    Guid ConversationId,
    Guid ClientMessageId,
    ActorType SenderRole,
    MessageType Type,
    string Content,
    string? AttachmentUrl,
    DateTimeOffset CreatedAt,
    DateTimeOffset? ReadAt);

/// <summary>
/// #58 body and hub SendMessage. clientMessageId = UUID generated by the app before sending: resending the same
/// message (retry after a timeout) returns the stored message instead of a duplicate.
/// TEXT: content 1–2000 chars. IMAGE: attachmentUrl from POST /files (purpose CHAT_IMAGE), content = optional caption.
/// </summary>
public sealed record SendMessageRequest(
    Guid ClientMessageId,
    MessageType Type,
    [StringLength(2000)] string? Content,
    [StringLength(500)] string? AttachmentUrl);

/// <summary>Hub SendMessage payload = <see cref="SendMessageRequest"/> + the conversation id.</summary>
public sealed record HubSendMessage(
    Guid ConversationId,
    Guid ClientMessageId,
    MessageType Type,
    string? Content,
    string? AttachmentUrl);

/// <summary>#56 open (or get) the conversation of a post with a partner.</summary>
public sealed record OpenConversationRequest(Guid ServiceRequestId, Guid PartnerProfileId);

/// <summary>#59 mark everything up to this message (from the other person) as read.</summary>
public sealed record MarkReadRequest(Guid LastReadMessageId);

/// <summary>
/// #57 page. History (cursor): newest → oldest, continue with nextCursor while hasMore.
/// Sync (after): oldest → newest after a known point, continue with syncCursor. syncCursor always points at the newest
/// message returned (or the given point), so a reconnecting app can call ?after=syncCursor.
/// </summary>
public sealed record MessagePage(IReadOnlyList<MessageDto> Items, string? NextCursor, string? SyncCursor, bool HasMore);

/// <summary>Server → caller after SendMessage on the hub (F-CHAT-04: the message is now SENT).</summary>
public sealed record MessageAck(Guid ClientMessageId, Guid MessageId, DateTimeOffset SentAt);

/// <summary>Server → both members after MarkRead / #59.</summary>
public sealed record MessageRead(Guid ConversationId, Guid UserId, Guid LastReadMessageId);

public sealed record UnreadCountDto(int Total);
